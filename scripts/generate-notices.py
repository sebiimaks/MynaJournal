#!/usr/bin/env python3
"""Render the reviewed licence snapshot; fail closed when Cargo.lock changes.

Python 3.11+; no downloads or third-party Python packages are used. Updating a
dependency requires reviewing its actual licence files and updating the snapshot
in licenses/ before this command can generate a new distribution notice.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys
import tomllib


ROOT = Path(__file__).resolve().parent.parent
SEPARATOR = "=" * 78
MPL_SOURCE_FILES = {
    ("option-ext", "0.2.0"): {
        ".cargo_vcs_info.json", ".gitignore", "Cargo.toml", "Cargo.toml.orig",
        "LICENSE.txt", "README.md", "src/impl.rs", "src/lib.rs",
    },
}


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def registry_snapshot(root):
    snapshot = json.loads((root / "licenses/registry.json").read_text())
    if snapshot.get("schema") != 1:
        raise ValueError("Unsupported dependency notice snapshot schema")
    with (root / "Cargo.lock").open("rb") as handle:
        lock = tomllib.load(handle)
    locked = {
        (p["name"], p["version"], p["source"]): p.get("checksum")
        for p in lock["package"] if p.get("source")
    }
    reviewed = {}
    for p in snapshot["packages"]:
        key = (p["name"], p["version"], p["source"])
        if key in reviewed:
            raise ValueError(f"Duplicate dependency notice: {key}")
        if not p.get("license") or not p.get("selected_license") or not p.get("notices"):
            raise ValueError(f"Incomplete dependency notice: {key}")
        if "MPL-2.0" in p["selected_license"]:
            expected = MPL_SOURCE_FILES.get((p["name"], p["version"]))
            actual = [record["label"] for record in p.get("source_files", [])]
            if expected is None or set(actual) != expected or len(actual) != len(expected):
                raise ValueError(f"Incomplete MPL source file inventory: {key}")
            for record in p["source_files"]:
                source = record["source"]
                if (source.get("crate"), source.get("version"), source.get("path")) != (
                    p["name"], p["version"], record["label"]
                ):
                    raise ValueError(f"Invalid MPL source provenance: {key}")
        reviewed[key] = p["checksum"]
    if reviewed != locked:
        added = sorted(set(locked) - set(reviewed))
        removed = sorted(set(reviewed) - set(locked))
        changed = sorted(k for k in set(locked) & set(reviewed) if locked[k] != reviewed[k])
        raise ValueError(
            "Cargo.lock differs from the reviewed licence snapshot. Review actual "
            "licences and update licenses/registry.json and licenses/texts.json first. "
            f"Added: {added}; removed: {removed}; changed checksums: {changed}"
        )
    return snapshot


def source_description(source):
    if "url" in source:
        return source["url"]
    return (f"https://crates.io/api/v1/crates/{source['crate']}/{source['version']}/download"
            f" :: {source['path']}")


def generate(root):
    snapshot = registry_snapshot(root)
    texts = json.loads((root / "licenses/texts.json").read_text())
    for digest, text in texts.items():
        if sha256(text.encode("utf-8")) != digest:
            raise ValueError(f"Notice text hash mismatch: {digest}")

    references = {}
    output = [
        "MynaJournal — third-party notices\n",
        "This file is generated by scripts/generate-notices.py from the reviewed\n"
        "Cargo.lock snapshot in licenses/. Keep it with binary distributions.\n"
        "MynaJournal's own MIT licence and attribution are in LICENSE and ATTRIBUTION.md.\n\n"
        "This inventory conservatively includes the entire locked dependency graph,\n"
        "including build tools and target-specific dependencies. Inclusion here does\n"
        "not imply that a component is linked into every binary. The component\n"
        "licences apply independently; MynaJournal does not relicense them.\n\n"
        "For alternative licences, the selected option is recorded per package;\n"
        "additional required licences (AND) still apply. Other licence texts may\n"
        "be retained to preserve the complete upstream notices. Authors listed\n"
        "below are the package's published authors, not newly asserted copyrights.\n\n"
        "libgit2 is GPLv2 with its explicit linking exception; its complete notice\n"
        "also contains the notices for bundled native components. The exception\n"
        "permits linking the unmodified library into this application. SQLite's\n"
        "core is public domain; its Rust wrapper has a separate MIT licence.\n\n"
        "option-ext 0.2.0 is used unchanged under MPL-2.0. Its complete published\n"
        "crate source (excluding Cargo's local cache marker) is reproduced in\n"
        "the source appendix below, under MPL-2.0, and is also available from\n"
        "https://crates.io/api/v1/crates/option-ext/0.2.0/download . The MPL rights\n"
        "in those files are not restricted by MynaJournal's MIT licence.\n\n"
        "Some upstream packages refer to a standard licence without publishing\n"
        "their own full text or copyright statement. For these, the referenced\n"
        "standard text is supplied with the upstream grant and package authors;\n"
        "template placeholders are not assertions of additional copyright.\n",
        SEPARATOR + "\nDEPENDENCY INVENTORY\n" + SEPARATOR,
    ]
    for package in snapshot["packages"]:
        identity = f"{package['name']} {package['version']}"
        output.append(f"\n{identity}\nDeclared licence: {package['license']}\n"
                      f"Selected licence: {package['selected_license']}\n"
                      f"Crate SHA-256: {package['checksum']}")
        if package.get("repository"):
            output.append("Repository: " + package["repository"])
        if package.get("authors"):
            output.append("Published authors: " + "; ".join(package["authors"]))
        if package.get("vcs_commit"):
            output.append("Published source revision: " + package["vcs_commit"])
        for record in package["notices"]:
            digest = record["sha256"]
            if digest not in texts:
                raise ValueError(f"Missing notice text for {identity}: {digest}")
            reference = f"{identity}: {record['label']}\nSource: {source_description(record['source'])}"
            references.setdefault(digest, []).append(reference)
            output.append(f"Notice [{digest}]: {record['label']}")

    output.append("\n" + SEPARATOR + "\nFULL LICENCE AND NOTICE TEXTS\n" + SEPARATOR)
    for digest, sources in references.items():
        output.append(f"\n{SEPARATOR}\nNOTICE [{digest}]\n" + "\n".join(sources))
        output.append(SEPARATOR + "\n" + texts[digest])

    output.append("\n" + SEPARATOR + "\nMPL-2.0 SOURCE APPENDIX\n" + SEPARATOR)
    source_count = 0
    for package in snapshot["packages"]:
        for record in package.get("source_files", []):
            source_count += 1
            digest = record["sha256"]
            if digest not in texts:
                raise ValueError(f"Missing MPL source text: {digest}")
            output.append(f"\n{SEPARATOR}\n{package['name']}-{package['version']}/{record['label']}\n"
                          f"SHA-256: {digest}\nSource: {source_description(record['source'])}\n{SEPARATOR}")
            output.append(texts[digest])
    if source_count == 0:
        raise ValueError("MPL source appendix is missing")

    runtime_dir = root / "licenses/runtime"
    runtime = json.loads((runtime_dir / "manifest.json").read_text())
    output.append("\n" + SEPARATOR + "\nNATIVE RUNTIME NOTICES\n" + SEPARATOR)
    for component in runtime["components"]:
        output.append(f"\n{component['name']} {component['version']}")
        for record in component["files"]:
            path = (runtime_dir / record["path"]).resolve()
            if not path.is_relative_to(runtime_dir.resolve()):
                raise ValueError("Runtime notice path escapes licenses/runtime")
            data = path.read_bytes()
            if sha256(data) != record["sha256"]:
                raise ValueError(f"Runtime notice hash mismatch: {path}")
            output.append(f"\n{SEPARATOR}\n{record['path']}\nSource: {record['source_url']}\n"
                          f"SHA-256: {record['sha256']}\n{SEPARATOR}\n" + data.decode("utf-8"))
    return "\n".join(output).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the existing generated notice")
    args = parser.parse_args()
    try:
        result = generate(ROOT)
        destination = ROOT / "THIRD_PARTY_NOTICES.txt"
        if args.check:
            if not destination.exists() or destination.read_bytes() != result:
                raise ValueError("THIRD_PARTY_NOTICES.txt is stale; run scripts/generate-notices.py")
            print("Third-party notice snapshot matches Cargo.lock and all notice/source hashes.")
        else:
            destination.write_bytes(result)
            print(f"Wrote {destination.name} ({len(result):,} bytes)")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Notice validation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
